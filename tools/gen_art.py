"""MONK-1's characters: the iOS port's drawings, packed for the FM-1.

  tools/gen_art.py import DIR     DIR = the iOS exporter's output (tools/ExportFM1Art.swift, run in
                                  monksynth-ios: scripts/test.sh MonkSynthTests/ExportFM1Art writes
                                  /tmp/fm1-monk-art): writes assets/characters/
  tools/gen_art.py OUT.h          the C header the firmware includes (tools/build.py runs this)

assets/characters/ holds, per character, the scene without the face (<id>.png, 240 x 240), the face
states stacked in one strip (<id>_face.png: blink 0/1 x loudness 0..4, each the face's rectangle),
a few reference frames with the mouth (ref/, for tests/host/raster_test.c) and characters.json
(names, colours, voices, the mouth's style, the face's rectangle).

The header: per character a 256-colour palette (the scene and its faces together, median cut, no
dither), the scene as 10 bands of 24 rows, each raw deflate with a 1 KB window (the firmware's
inflate.c), the face patches (identical ones once), the region a frame redraws (face, mouth and what
sits over the mouth), and the voice. The mouth itself is drawn by the firmware (app/raster.c)."""
import json
import sys
import zlib
from pathlib import Path

from PIL import Image, ImageChops

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets" / "characters"
ORDER = ["monk", "fish", "unicorn", "girl", "oldman", "cow", "firefighter", "punk", "dog", "pizza", "ghost", "cat"]
SIDE = 240
BAND = 24
U = SIDE / 300.0                      # px per stage unit
STATES = [(b, l) for b in (0, 1) for l in range(5)]
PARAMS = ["portTime", "vowel", "delay", "headSize", "vibrato", "vibratoRate", "aspiration", "attack", "decay",
          "sustain", "release", "unison", "unisonDetune", "delayRate", "level", "unisonVoiceSpread", "pitchBend"]
SCENE_H = 190                         # the knob strip starts here: nothing dynamic may reach it
REFS = [(0, 0), (0, 4), (12, 0), (12, 4), (17, 2), (23, 4)]
OVER = {  # stage-unit bounds of what each character draws over its mouth (CharacterView: drawOverMouth)
    "oldman": (108 - 3, 148 - 3, 192 + 3, 166 + 3),
    "firefighter": (118 - 3, 156 - 3, 182 + 3, 172 + 3),
    "cat": (70 - 2, 140 - 2, 230 + 2, 162 + 2),
}


def bbox_union(a, b):
    if a is None:
        return b
    if b is None:
        return a
    return (min(a[0], b[0]), min(a[1], b[1]), max(a[2], b[2]), max(a[3], b[3]))


def cmd_import(src):
    src = Path(src)
    meta = json.loads((src / "characters.json").read_text())
    (ASSETS / "ref").mkdir(parents=True, exist_ok=True)
    for c in meta["characters"]:
        cid = c["id"]
        base = Image.open(src / f"{cid}_base.png").convert("RGB")
        faces = [Image.open(src / f"{cid}_face_b{b}_l{l}.png").convert("RGB") for b, l in STATES]
        box = None
        for f in faces:
            box = bbox_union(box, ImageChops.difference(base, f).getbbox())
        x0, y0, x1, y1 = box
        strip = Image.new("RGB", (x1 - x0, (y1 - y0) * len(faces)))
        for i, f in enumerate(faces):
            strip.paste(f.crop(box), (0, i * (y1 - y0)))
        base.save(ASSETS / f"{cid}.png", optimize=True)
        strip.save(ASSETS / f"{cid}_face.png", optimize=True)
        c["face"] = list(box)
        for v, l in REFS:
            Image.open(src / f"{cid}_ref_v{v}_l{l}.png").convert("RGB").save(ASSETS / "ref" / f"{cid}_v{v}_l{l}.png", optimize=True)
    meta["characters"].sort(key=lambda c: ORDER.index(c["id"]))
    (ASSETS / "characters.json").write_text(json.dumps(meta, indent=1, sort_keys=True) + "\n")
    print(f"imported {len(meta['characters'])} characters into {ASSETS}")


def rgb565(h):
    v = int(h, 16) if isinstance(h, str) else h
    r, g, b = (v >> 16) & 255, (v >> 8) & 255, v & 255
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def deflate(data):
    co = zlib.compressobj(9, zlib.DEFLATED, -10, 9)
    return co.compress(bytes(data)) + co.flush()


def mouth_bounds(m):
    """the mouth's widest reach over every vowel and loudness (ToonMouth.draw: OO..EE, boost 1.35)"""
    s, cx, cy = m["scale"], m["x"], m["y"]
    sw = (17 * s if m["variant"] == "lips" else 5 * max(0.8, s)) / 2 + 1
    w, h = 74 * s, 56 * s * 1.35
    return (cx - w / 2 - sw, cy - 0.42 * h - sw, cx + w / 2 + sw, cy + 0.58 * h + sw)


def carr(name, ctype, vals, per=16):
    out = [f"static const {ctype} {name}[{len(vals)}] = {{"]
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    out.append("};")
    return out


def cmd_header(out_path):
    meta = json.loads((ASSETS / "characters.json").read_text())
    shades = meta["shades"]
    lines = ["/* GENERATED by tools/gen_art.py from assets/characters/ (the iOS port's drawings): do not edit */",
             "#pragma once", f"#define ART_N {len(meta['characters'])}", f"#define ART_BAND {BAND}",
             f"#define ART_NBANDS {SIDE // BAND}", f"#define ART_SCENE_H {SCENE_H}",
             f"#define ART_SHADE_HAIR 0x{rgb565(shades['F4F3EE']):04X}u",
             f"#define ART_SHADE_MOUSTACHE 0x{rgb565(shades['7A3D22']):04X}u", ""]
    total = 0
    entries = []
    for ci, c in enumerate(meta["characters"]):
        cid = c["id"]
        base = Image.open(ASSETS / f"{cid}.png").convert("RGB")
        strip = Image.open(ASSETS / f"{cid}_face.png").convert("RGB")
        fx0, fy0, fx1, fy1 = c["face"]
        fw, fh = fx1 - fx0, fy1 - fy0
        both = Image.new("RGB", (SIDE, SIDE + strip.height))
        both.paste(base, (0, 0))
        both.paste(strip, (0, SIDE))
        q = both.quantize(256, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
        pal = q.getpalette()[:768]
        idx = q.tobytes()
        w = SIDE
        pal565 = []
        for i in range(256):
            r, g, b = (pal[3 * i:3 * i + 3] + [0, 0, 0])[:3] if 3 * i + 2 < len(pal) else (0, 0, 0)
            v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
            pal565.append(f"0x{((v >> 8) | (v << 8)) & 0xFFFF:04X}")   # byte-swapped, as the canvas holds it
        blob, offs = bytearray(), []
        for y in range(0, SIDE, BAND):
            offs.append(len(blob))
            blob += deflate(idx[y * w:(y + BAND) * w])
        offs.append(len(blob))
        uniq, fidx, foffs, fblob = {}, [], [], bytearray()
        for s in range(len(STATES)):
            patch = bytearray()
            for y in range(fh):
                row0 = (SIDE + s * fh + y) * w
                patch += idx[row0:row0 + fw]
            key = bytes(patch)
            if key not in uniq:
                uniq[key] = len(foffs)
                foffs.append(len(fblob))
                fblob += deflate(patch)
            fidx.append(uniq[key])
        foffs.append(len(fblob))
        reg = bbox_union((fx0, fy0, fx1, fy1), tuple(int(round(v * U)) for v in mouth_bounds(c["mouth"])))
        if cid in OVER:
            reg = bbox_union(reg, tuple(int(round(v * U)) for v in OVER[cid]))
        rx0, ry0 = max(0, reg[0] - 1), max(0, reg[1] - 1)
        rx1, ry1 = min(SIDE, reg[2] + 2), min(SIDE, reg[3] + 2)
        if ry1 > SCENE_H:
            raise SystemExit(f"{cid}: the region reaches row {ry1}, into the knob strip ({SCENE_H})")
        if (rx1 - rx0) * (ry1 - ry0) > 16384 or rx1 - rx0 > 256:
            raise SystemExit(f"{cid}: the region is larger than face.c's buffers (RS_COV)")
        lines += carr(f"PAL_{ci}", "uint16_t", pal565, 12)
        lines += carr(f"BASE_{ci}", "uint8_t", list(blob), 24)
        lines += carr(f"BOFF_{ci}", "uint32_t", offs, 12)
        lines += carr(f"FACE_{ci}", "uint8_t", list(fblob), 24)
        lines += carr(f"FOFF_{ci}", "uint32_t", foffs, 12)
        total += len(blob) + len(fblob) + 512
        m = c["mouth"]
        p = c["params"]
        entries.append(
            f'    {{"{cid}", "{c["name"]}", 0x{rgb565(c["accent"]):04X}u, PAL_{ci}, BASE_{ci}, BOFF_{ci}, FACE_{ci}, FOFF_{ci},\n'
            f'     {{{", ".join(str(i) for i in fidx)}}}, {fx0}, {fy0}, {fw}, {fh}, {rx0}, {ry0}, {rx1 - rx0}, {ry1 - ry0},\n'
            f'     {m["x"]:.1f}f, {m["y"]:.1f}f, {m["scale"]:.3f}f, ART_{m["variant"].upper()}, 0x{rgb565(m["lip"]):04X}u,\n'
            f'     {{{", ".join(f"{p[k]:.6f}f" for k in PARAMS)}}}}},')
    lines += ["", "enum { ART_LIPS, ART_MUZZLE, ART_BARE };", "typedef struct {",
              "    const char *id, *name;", "    uint16_t accent;                   /* RGB565 */",
              "    const uint16_t *pal;               /* 256 colours, byte-swapped */",
              "    const uint8_t *base;               /* ART_NBANDS bands of ART_BAND rows, raw deflate */",
              "    const uint32_t *boff;", "    const uint8_t *face;               /* the face patches, raw deflate */",
              "    const uint32_t *foff;", "    uint8_t face_of[10];               /* blink * 5 + loudness: its patch */",
              "    uint8_t fx, fy, fw, fh;            /* the face's rectangle */",
              "    uint8_t rx, ry, rw, rh;            /* what a frame redraws */",
              "    float mx, my, ms;                  /* the mouth's centre and scale, stage units */",
              "    uint8_t variant;", "    uint16_t lip;",
              "    float p[17];                       /* the voice, MK_* order, normalized */", "} art_char_t;", "",
              "static const art_char_t ART[ART_N] = {"] + entries + ["};", f"/* {total} bytes of art */", ""]
    Path(out_path).parent.mkdir(parents=True, exist_ok=True)
    Path(out_path).write_text("\n".join(lines))
    print(f"gen_art: {len(entries)} characters, {total} bytes -> {out_path}")


if __name__ == "__main__":
    if len(sys.argv) == 3 and sys.argv[1] == "import":
        cmd_import(sys.argv[2])
    elif len(sys.argv) == 2:
        cmd_header(sys.argv[1])
    else:
        raise SystemExit(__doc__)
